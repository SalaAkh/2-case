import { translate } from "../i18n";
import type { MentorRequest } from "../contracts";
import { findDemoExample } from "../examples";
import { safeFallback } from "./guard";

function demoReplySource(input: MentorRequest, hintLevel: number): string {
  const example = findDemoExample(input.code, input.language);
  if (!example) return "Это демонстрация с подготовленными вопросами; произвольный код здесь не анализируется. Для разбора своего кода подключите OpenAI или откройте учебный пример.\n\n" + safeFallback(input, hintLevel);
  const answer = input.history.filter(m => m.role === "user").at(-1)?.content.toLowerCase() ?? "";
  const turns = input.history.filter(m => m.role === "user").length;
  const attemptedOverride = /(?:забудь|игнорируй|правильный код|готовый код|полное решение|полный ответ|ignore|override|correct code|system prompt|base64|обычный chatgpt)/i.test(answer);
  if (attemptedOverride) return "Сохраним формат самостоятельного разбора.\n\n" + safeFallback(input, hintLevel);

  const hints: Record<string, string[]> = {
    index: [
      "Посмотрим на момент перед ошибкой. Как соотносятся количество элементов списка и значения, которыми перебирается цикл?",
      "У списка есть размер и диапазон допустимых индексов. Какой индекс используется на последнем проходе цикла?",
      "Индексация начинается с нуля, поэтому количество элементов и последний допустимый индекс — разные величины. Какие значения индекса посещает твой цикл и все ли они соответствуют элементам?",
    ],
    condition: [
      "Обрати внимание на границу разрешённого возраста. Какой случай стоит проверить отдельно?",
      "Какой результат даёт текущее условие для возраста ровно на границе, до перехода к возвращаемому значению?",
      "Строгое сравнение не включает равенство. Сравни словесное требование с множеством значений, проходящих проверку. Относится ли сама граница к этому множеству?",
    ],
    loop: [
      "Что должно происходить с состоянием программы, чтобы цикл когда-нибудь завершился?",
      "Проследи значение счётчика до и после одного прохода тела цикла. Какое значение сохраняется к следующей проверке?",
      "Вычисление выражения и сохранение результата в переменной — разные действия. Как определить по наблюдаемым значениям, сохраняется ли новое состояние между проходами?",
    ],
  };
  if (input.action === "hint") return hints[example.topic][Math.max(0, hintLevel - 1)];
  if (input.action === "start") return {
    index: "Давай исследуем границы списка. Ошибка появляется после вывода чисел — это полезное наблюдение.\n\nСколько элементов в списке и с какого индекса начинается их нумерация?",
    condition: "Начнём с самого небольшого примера, на котором ожидание расходится с результатом.\n\nЧто вернёт сама проверка возраста для пользователя, которому ровно 18?",
    loop: "Рассмотрим один проход цикла, чтобы понять, какое состояние получает следующий.\n\nКакое значение у счётчика до и после первого прохода?",
  }[example.topic];
  if (example.topic === "index") {
    if (/(?:5|пять|five|бес)/.test(answer) && /последнем проходе|last iteration|соңғы қайталан/iu.test(input.history.at(-2)?.content ?? "")) return "Теперь у тебя есть два наблюдения: допустимая граница и фактический индекс.\n\nКак они соотносятся и какой самостоятельной проверкой ты подтвердишь свою гипотезу?";
    if (/^(?:5|пять|five|бес)(?:\s|[,.;!?]|$)/.test(answer) && !/индекс.*(?:4|четыр|four|төрт)/.test(answer)) return "Ты указал количество элементов. Индекс отсчитывается отдельно.\n\nКакой индекс у последнего элемента, если первый имеет индекс ноль?";
    if (/(?:4|четыр|four|төрт)/.test(answer)) return "Теперь сравним границу списка с поведением цикла.\n\nКакое значение принимает переменная цикла на самом последнем проходе?";
    if (/(?:лишн|границ|выход|допустим|индекс|index|bound|extra|шекара|артық)/.test(answer) && turns > 1) return "Сформулированную гипотезу стоит проверить самостоятельно.\n\nКакие два списка разного размера ты выберешь для проверки и какое поведение ожидаешь?";
    return "Давай проверим это предположение на одном проходе.\n\n" + safeFallback(input, hintLevel);
  }
  if (example.topic === "condition") {
    if (/(?:false|лож|нет|не проходит|неверн|no|false|жалған|жоқ)/.test(answer)) return "Ты описал результат проверки на границе.\n\nВключает ли словесное требование сам граничный возраст и совпадает ли это с наблюдением?";
    if (/(?:равен|включ|границ|строг|equal|includ|bound|strict|тең|шекара|қатаң)/.test(answer)) return "Проверим твоё понимание на соседних значениях.\n\nКакие результаты ты ожидаешь для возраста чуть ниже границы, ровно на ней и чуть выше?";
    return safeFallback(input, hintLevel);
  }
  if (/(?:нол|0|не меня|не измен|остаётся|остается|zero|unchanged|same|нөл|өзгерм|қалады)/.test(answer)) return "Ты заметил, что состояние остаётся прежним.\n\nЧем отличается вычисление нового значения от его сохранения для следующего прохода?";
  if (/(?:сохран|присва|запис|save|assign|store|сақта|меншікт)/.test(answer)) return "Свяжем это наблюдение с завершением цикла.\n\nКак ты самостоятельно проверишь, что состояние меняется и условие остановки однажды выполняется?";
  return safeFallback(input, hintLevel);
}

export function demoReply(input: MentorRequest, hintLevel: number): string {
  return translate(input.locale ?? "ru", demoReplySource(input, hintLevel));
}
